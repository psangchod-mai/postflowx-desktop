// Build key set + reverse maps so switching languages always works.
const KEY_SET = new Set();
const REVERSE = {};
for (const [lang, map] of Object.entries(DICT)){
  if (lang === 'en') continue;
  REVERSE[lang] = {};
  for (const [k, v] of Object.entries(map || {})){
    KEY_SET.add(k);
    if (typeof v === 'string' && v.trim()){
      REVERSE[lang][v.trim()] = k;
    }
  }
}

function _candKeys(s){
  const t = String(s ?? '').trim();
  const u = t.toUpperCase();
  const l = t.toLowerCase();
  const c = t.replace(/\s+/g, ' ');
  const cu = c.toUpperCase();
  const cl = c.toLowerCase();
  const out = [];
  for (const x of [t, c, u, l, cu, cl]){
    if (x && !out.includes(x)) out.push(x);
  }
  return out;
}

function toEnglishKey(raw){
  const candidates = _candKeys(raw);
  for (const c of candidates){
    if (KEY_SET.has(c)) return c;
  }
  for (const c of candidates){
    for (const lang of Object.keys(REVERSE)){
      const k = REVERSE[lang]?.[c];
      if (k) return k;
    }
  }
  return String(raw ?? '').trim();
}

function normLang(lang){
  const raw = String(lang || "").trim();
  if (!raw) return "en";
  const lower = raw.toLowerCase();
  if (lower === "zh" || lower === "zh-tw" || lower === "zh_hant" || lower === "zh-hant" || lower === "tw") return "zh-TW";
  if (lower.startsWith("zh-hant") || lower.startsWith("zh-tw") || lower.startsWith("zh_tw") || lower.endsWith("-tw")) return "zh-TW";
  if (lower.startsWith("zh")) return "zh-TW";
  if (lower === "kr" || lower.startsWith("ko") || lower.endsWith("-kr")) return "ko";
  if (lower === "jp" || lower.startsWith("ja") || lower.endsWith("-jp")) return "ja";
  if (lower.startsWith("th")) return "th";
  if (lower === "in" || lower.startsWith("id")) return "id";
  if (lower == "ph" || lower.startsWith("ph-") || lower.endsWith("-ph")) return "fil";
  if (lower.startsWith("fil") || lower.startsWith("tl")) return "fil";
  return "en";
}

export function getLang(){
  const raw = localStorage.getItem(STORAGE_KEY);
  if (raw) return normLang(raw);
  try{
    const prefs = Array.isArray(navigator?.languages) && navigator.languages.length
      ? navigator.languages
      : [navigator?.language, navigator?.userLanguage, navigator?.browserLanguage];
    for (const cand of prefs){
      const norm = normLang(cand || "");
      if (norm && norm !== "en") return norm;
      if (String(cand || "").toLowerCase() === 'en') return 'en';
    }
  }catch{}
  return normLang(navigator?.language || "en");
}

export function setLang(lang){
  const v = normLang(lang);
  localStorage.setItem(STORAGE_KEY, v);
  applyI18n(v);
}

export function t(str, langOverride){
  const lang = normLang(langOverride || getLang());
  const map = DICT[lang] || {};
  return map[str] || str;
}

function translateTextNode(node, lang){
  const raw = node.textContent ?? '';
  let saved = _ORIG_TEXT.get(node);
  if (!saved){
    const lead = String(raw).match(/^\s*/)?.[0] || "";
    const tail = String(raw).match(/\s*$/)?.[0] || "";
    const trimmed = String(raw).trim();
    if (!trimmed) return;
    const key = toEnglishKey(trimmed);
    saved = { lead, tail, key };
    _ORIG_TEXT.set(node, saved);
  }

  const key = saved.key;
  if (!key) return;

  if (lang === 'en'){
    const desired = `${saved.lead}${key}${saved.tail}`;
    if ((node.textContent ?? '') !== desired) node.textContent = desired;
    return;
  }

  const map = DICT[lang] || {};
  const out = map[key] || null;
  if (!out) return;
  const desired = `${saved.lead}${out}${saved.tail}`;
  if ((node.textContent ?? '') !== desired) node.textContent = desired;
}

function walk(node, fn){
  const stack = [node];
  while (stack.length){
    const cur = stack.pop();
    fn(cur);
    if (cur && cur.childNodes && cur.childNodes.length){
      for (let i = cur.childNodes.length - 1; i >= 0; i--) stack.push(cur.childNodes[i]);
    }
  }
}

function translateAttrs(el, L){
  if (!el || el.nodeType !== 1) return;

  // placeholders
  if (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement){
    const orig = el.getAttribute("data-i18n-ph-orig") || el.getAttribute("placeholder") || "";
    if (!el.getAttribute("data-i18n-ph-orig") && orig) el.setAttribute("data-i18n-ph-orig", orig);
    if (!orig) return;
    const key = toEnglishKey(orig);
    const desired = (L === 'en') ? key : (DICT[L]?.[key] || orig);
    if ((el.getAttribute('placeholder') || '') !== desired) el.setAttribute('placeholder', desired);
  }

  // title
  if (el.hasAttribute?.('title')){
    const orig = el.getAttribute("data-i18n-title-orig") || el.getAttribute("title") || "";
    if (!el.getAttribute("data-i18n-title-orig") && orig) el.setAttribute("data-i18n-title-orig", orig);
    if (orig){
      const key = toEnglishKey(orig);
      const desired = (L === 'en') ? key : (DICT[L]?.[key] || orig);
      if ((el.getAttribute('title') || '') !== desired) el.setAttribute('title', desired);
    }
  }

  // aria-label
  if (el.hasAttribute?.('aria-label')){
    const orig = el.getAttribute("data-i18n-aria-orig") || el.getAttribute("aria-label") || "";
    if (!el.getAttribute("data-i18n-aria-orig") && orig) el.setAttribute("data-i18n-aria-orig", orig);
    if (orig){
      const key = toEnglishKey(orig);
      const desired = (L === 'en') ? key : (DICT[L]?.[key] || orig);
      if ((el.getAttribute('aria-label') || '') !== desired) el.setAttribute('aria-label', desired);
    }
  }

  // <option> text for dropdowns
  if (el instanceof HTMLOptionElement){
    const orig = el.getAttribute('data-i18n-opt-orig') || el.textContent || '';
    if (!el.getAttribute('data-i18n-opt-orig') && orig) el.setAttribute('data-i18n-opt-orig', orig);
    if (!orig) return;
    const key = toEnglishKey(orig);
    const desired = (L === 'en') ? key : (DICT[L]?.[key] || orig);
    if ((el.textContent || '') !== desired) el.textContent = desired;
  }
}

function pauseObserver(){
  try{ _OBS?.disconnect?.(); }catch{}
}

function resumeObserver(){
  try{ if (_OBS && _OBS_OPTS) _OBS.observe(document.body, _OBS_OPTS); }catch{}
}

export function applyI18n(lang){
  const L = normLang(lang);
  document.documentElement.setAttribute("lang", L);

  _APPLYING = true;
  pauseObserver();
  try{
    walk(document.body, (n) => {
      if (!n) return;
      if (n.nodeType === 1){
        const tag = n.tagName?.toLowerCase?.() || "";
        if (tag === "script" || tag === "style") return;
        translateAttrs(n, L);
      }
      if (n.nodeType === 3){
        translateTextNode(n, L);
      }
    });
    try{
      const sel = document.getElementById('langSelect');
      if (sel && sel.value !== L) sel.value = L;
    }catch{}
  }finally{
    resumeObserver();
    _APPLYING = false;
  }
}

function applyI18nTo(root, L){
  if (!root) return;
  _APPLYING = true;
  pauseObserver();
  try{
    walk(root, (n)=>{
      if (!n) return;
      if (n.nodeType === 1){
        const tag = n.tagName?.toLowerCase?.() || "";
        if (tag === "script" || tag === "style") return;
        translateAttrs(n, L);
      }
      if (n.nodeType === 3){
        translateTextNode(n, L);
      }
    });
  }finally{
    resumeObserver();
    _APPLYING = false;
  }
}

function initI18nObserver(){
  if (_OBS) return;

  const pending = new Set();
  const schedule = ()=>{
    if (_RAF) return;
    _RAF = requestAnimationFrame(()=>{
      _RAF = 0;
      const L = getLang();
      const items = Array.from(pending);
      pending.clear();
      for (const n of items){
        try{ applyI18nTo(n, L); }catch{}
      }
    });
  };

  _OBS = new MutationObserver((muts)=>{
    if (_APPLYING) return;
    for (const m of muts){
      if (m.type === 'childList'){
        if (m.addedNodes && m.addedNodes.length){
          for (const n of m.addedNodes){
            if (n) pending.add(n);
          }
        }
      } else if (m.type === 'attributes'){
        if (m.target) pending.add(m.target);
      }
    }
    schedule();
  });

  try{
    _OBS_OPTS = {
      childList: true,
      subtree: true,
      attributes: true,
      attributeFilter: ['title','placeholder','aria-label'],
    };
    _OBS.observe(document.body, _OBS_OPTS);
  }catch{}
}

export function initI18nUI(){
  const sel = document.getElementById("langSelect");
  if (!sel) return;

  const cur = getLang();
  sel.value = cur;
  // Defer apply so the native <select> popup can close cleanly before
  // we mutate DOM/option text (prevents popup flicker/loop).
  sel.addEventListener("change", () => {
    const v = sel.value;
    requestAnimationFrame(()=> setLang(v));
  });
  applyI18n(cur);

  // Translate popups / dynamic DOM safely.
  initI18nObserver();
}

